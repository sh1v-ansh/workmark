// Re-inserts the 4 real students and 1 real listing (captured by
// export-production-data.mjs) into the rebuilt v0.5 schema.
//
// Run schema.sql AND seed_skills_taxonomy.sql against the live database
// FIRST — this script depends on the taxonomy already existing so it can
// resolve the listing's required_skills to real skill_ids.
//
// auth.users is untouched by schema.sql, so the 4 students keep their
// existing id — this script re-inserts by that same id and they stay
// logged in with no password reset needed.
//
// Deliberately NOT migrated (disposable, will regenerate):
//   - github_connections / repo scan history — the old OAuth-token model
//     is incompatible with the new GitHub App (installation-based) model.
//     These 3 students will reconnect via the new flow once Phase 1 ships.
//   - github_evidenced_skills / github_repo_profiles (38 + 58 rows) — old
//     free-text "priors," never evidence, will be regenerated by the next
//     scan under the new model. Not worth the canonicalization effort for
//     data that's about to be superseded anyway.
//
// Usage:
//   node --env-file=.env.local scripts/reinsert-production-data.mjs <export-file.json>

import { createClient } from '@supabase/supabase-js'
import { readFileSync, readdirSync } from 'fs'

const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL
const SERVICE_ROLE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY

if (!SUPABASE_URL || !SERVICE_ROLE_KEY) {
  console.error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY.')
  console.error('Run with: node --env-file=.env.local scripts/reinsert-production-data.mjs <export-file.json>')
  process.exit(1)
}

const admin = createClient(SUPABASE_URL, SERVICE_ROLE_KEY, {
  auth: { autoRefreshToken: false, persistSession: false },
})

// Known mapping from the listing's free-text required_skills to taxonomy
// slugs. 'Claude Design' has no entry — it was removed from the taxonomy
// (no known detection mechanism) and is deliberately dropped here, logged
// as unmapped rather than silently discarded.
const SKILL_ALIAS_MAP = {
  'prompt engineering': 'prompt-engineering',
  'claude code': 'claude-code',
  'fastapi': 'fastapi',
  'render': 'render',
  'postgresql': 'postgresql',
  'vercel': 'vercel',
  'posthog': 'posthog',
  'vite': 'vite',
}

// Every required skill gets the same starting weight — level_i is an
// IMPORTANCE weight now (§7), not a difficulty threshold, and there's no
// principled way to infer relative importance from free text alone. The
// listing's real poster should adjust these once the edit UI exists.
const DEFAULT_REQUIRED_LEVEL = 3

function slugifyHandle(fullName, taken) {
  const base = (fullName ?? 'student').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '') || 'student'
  let candidate = base
  let n = 2
  while (taken.has(candidate)) {
    candidate = `${base}-${n}`
    n++
  }
  taken.add(candidate)
  return candidate
}

function findExportFile() {
  const arg = process.argv[2]
  if (arg) return arg
  const candidates = readdirSync('.').filter((f) => /^export-.*\.json$/.test(f)).sort()
  if (candidates.length === 0) {
    console.error('No export-*.json file found in the current directory, and none given as an argument.')
    console.error('Run: node --env-file=.env.local scripts/reinsert-production-data.mjs <export-file.json>')
    process.exit(1)
  }
  return candidates[candidates.length - 1] // most recent by timestamp-sortable filename
}

async function main() {
  const exportFile = findExportFile()
  console.log(`Reading ${exportFile}...\n`)
  const dump = JSON.parse(readFileSync(exportFile, 'utf-8'))

  const authById = new Map(dump.auth_users.map((u) => [u.id, u]))
  const takenHandles = new Set()

  // ── Students ──────────────────────────────────────────────────────────
  console.log('Re-inserting students...')
  for (const s of dump.students) {
    const auth = authById.get(s.id)
    const eduDomain = auth?.email?.split('@')[1] ?? null
    const handle = slugifyHandle(s.full_name, takenHandles)

    const { error } = await admin.from('students').insert({
      id: s.id,
      full_name: s.full_name,
      university: s.university,
      major: s.major,
      degree_type: s.degree_type,
      graduation_year: s.graduation_year,
      gpa: s.gpa,
      is_international: s.is_international ?? false,
      visa_type: s.visa_type,
      skills: s.skills,  // self-reported, display only — carried over verbatim
      github_url: s.github_url,
      github_username: null,  // old OAuth-based connection is incompatible with the new GitHub App model — reconnect required
      linkedin_url: s.linkedin_url,
      availability: s.availability,
      hours_per_week: s.hours_per_week,
      available_from: s.available_from,
      open_to_collab: s.open_to_collab ?? false,
      handle,
      edu_domain: eduDomain,
      edu_verified_at: s.created_at ?? new Date().toISOString(),
      created_at: s.created_at,
    })
    if (error) throw error
    console.log(`  ${s.full_name} — handle: ${handle}, edu_domain: ${eduDomain}`)
  }

  // ── Listing ───────────────────────────────────────────────────────────
  console.log('\nRe-inserting listing(s)...')
  for (const p of dump.projects) {
    if (p.poster_type !== 'student') {
      console.log(`  SKIPPED "${p.title}" — poster_type '${p.poster_type}' has no MVP equivalent (student-only in this schema version)`)
      continue
    }

    const { data: listing, error: listingErr } = await admin.from('listings').insert({
      id: p.id,
      poster_id: p.poster_id,
      poster_type: 'student',
      poster_display_name: p.poster_display_name,
      title: p.title,
      brief: p.description,
      est_hours: null,
      hours_per_week: p.hours_per_week,
      duration: p.duration,
      work_mode: p.work_mode,
      team_size: p.team_size,
      declared_difficulty: null,  // no principled derivation from the old free-text data — poster should set this
      requires_prior_evidence: false,
      is_paid: false,  // forced — MVP schema has no payments infra; original is_paid value, if true, cannot be honored
      tier: 'listing_driven',
      status: p.is_open ? 'open' : 'closed',
      view_count: p.view_count ?? 0,
      created_at: p.created_at,
    }).select().single()
    if (listingErr) throw listingErr
    console.log(`  "${p.title}" (${listing.id})`)

    const unmapped = []
    const requirements = []
    for (const raw of p.required_skills ?? []) {
      const slug = SKILL_ALIAS_MAP[raw.trim().toLowerCase()]
      if (slug) {
        requirements.push({ listing_id: listing.id, skill_id: slug, required_level: DEFAULT_REQUIRED_LEVEL })
      } else {
        unmapped.push(raw)
      }
    }
    if (requirements.length > 0) {
      const { error: reqErr } = await admin.from('listing_requirements').insert(requirements)
      if (reqErr) throw reqErr
    }
    console.log(`    mapped: ${requirements.map((r) => r.skill_id).join(', ') || '(none)'}`)
    if (unmapped.length > 0) {
      console.log(`    UNMAPPED (dropped, not in taxonomy): ${unmapped.join(', ')}`)
    }
  }

  console.log('\nDone. Not migrated (see file header for why): github_connections, github_evidenced_skills, github_repo_profiles.')
  console.log('Every required_level defaulted to 3 (medium importance) — review and adjust in the UI once it exists.')
  console.log('Every listing\'s declared_difficulty is null — same reason, no principled way to derive it from the old data.')
}

main().catch((err) => {
  console.error('\nRe-insertion failed:', err.message ?? err)
  process.exit(1)
})
